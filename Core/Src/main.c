  HAL_NVIC_SetPriority(TIM2_IRQn, 1, 0);
  HAL_NVIC_EnableIRQ(TIM2_IRQn);

  /* USART2 发送中断：只负责把遥测帧搬出去，优先级低于控制环 */
  HAL_NVIC_SetPriority(USART2_IRQn, 2, 0);
  HAL_NVIC_EnableIRQ(USART2_IRQn);

  /* 微秒延时/时间戳依赖 DWT，必须先于软件 I2C 与编码器初始化 */
  Delay_Init();

  /* 编码器：两路硬件 I2C（I2C1/I2C2，100kHz） */
  MagneticSensor_Init();

  /* IMU：软件 I2C（PA0/PA1） */
  MPU6050_Init();

  /* 电机：启动 PWM 并做零电角标定，每个电机阻塞约 3s */
  Motor_Init(&motor_left);
  Motor_Init(&motor_right);

  /* 标定结束后再开 2ms 速度环中断（TIM2: 72MHz/72/2000 = 500Hz） */
  HAL_TIM_Base_Start_IT(&htim2);

  uint32_t t_slow = HAL_GetTick();
  /* USER CODE END 2 */

